// ── Rate Limiter Engine (Per-User / Client Storage Window) ───────────────
const RATE_LIMIT_KEY_PREFIX = 'secloudive_ratelimit_sim_'
const MAX_SIMULATION_REQUESTS = 10
const RATE_LIMIT_WINDOW_MS = 30000 // 30 seconds

function checkClientRateLimit(userId) {
  try {
    const key = `${RATE_LIMIT_KEY_PREFIX}${userId || 'anonymous'}`
    const now = Date.now()
    const raw = localStorage.getItem(key)
    let timestamps = raw ? JSON.parse(raw) : []
    // Filter out timestamps outside window
    timestamps = timestamps.filter(t => now - t < RATE_LIMIT_WINDOW_MS)

    if (timestamps.length >= MAX_SIMULATION_REQUESTS) {
      const waitSec = Math.ceil((RATE_LIMIT_WINDOW_MS - (now - timestamps[0])) / 1000)
      return { allowed: false, waitSeconds: Math.max(1, waitSec) }
    }

    timestamps.push(now)
    localStorage.setItem(key, JSON.stringify(timestamps))
    return { allowed: true }
  } catch {
    return { allowed: true }
  }
}


// =========================================================================
// SeCloudive - AWS Security Cheat Sheet & Study Guide Modal
// High-Yield Interactive Viewer with Print / Save as PDF and Markdown Download
// =========================================================================

import { useState } from 'react'
import {
  Printer,
  Copy,
  Check,
  Download,
  X,
  BookOpen,
  Award,
  Zap,
  Terminal,
  ShieldCheck
} from 'lucide-react'
import { playTactileClick } from '../utils/cyberMotionAudio'

export default function AwsCheatSheetModal({ cheatSheet, onClose }) {
  const [copied, setCopied] = useState(false)

  if (!cheatSheet) return null

  const handlePrint = () => {
    playTactileClick()
    window.print()
  }

  const formatAsMarkdown = () => {
    let md = `# ${cheatSheet.title}\n`
    md += `## ${cheatSheet.subtitle}\n`
    md += `Category: ${cheatSheet.category} | Platform: SeCloudive\n\n`
    md += `${cheatSheet.description}\n\n`
    md += `================================================================================\n\n`

    cheatSheet.sections.forEach(sec => {
      md += `### ${sec.heading}\n\n`
      sec.items.forEach(item => {
        md += `* **${item.key}** (${item.operator})\n`
        md += `  - Purpose: ${item.purpose}\n`
        md += `  - Syntax/Example:\n    \`\`\`\n    ${item.example}\n    \`\`\`\n\n`
      })
    })

    md += `---\n*Generated by SeCloudive Cloud Security Career OS (100% Free Educational Resource)*\n`
    return md
  }

  const handleCopyMarkdown = () => {
    playTactileClick()
    const md = formatAsMarkdown()
    navigator.clipboard.writeText(md)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  const handleDownloadMarkdown = () => {
    playTactileClick()
    const md = formatAsMarkdown()
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `${cheatSheet.id}.md`
    document.body.appendChild(a)
    a.click()
    document.body.removeChild(a)
    URL.revokeObjectURL(url)
  }

  return (
    <div className="cert-modal-backdrop" onClick={onClose} style={{ zIndex: 10000 }}>
      <div 
        className="cert-modal-dialog" 
        onClick={e => e.stopPropagation()} 
        style={{ maxWidth: '900px', maxHeight: '90vh', overflowY: 'auto', background: '#0a0f1d' }}
        role="dialog"
        aria-modal="true"
        aria-label={cheatSheet.title}
      >
        {/* Top Control Bar (Hidden during Print) */}
        <div className="cert-modal-controls no-print" style={{ padding: '16px 24px', borderBottom: '1px solid rgba(148, 163, 184, 0.15)', background: 'rgba(15, 23, 42, 0.9)' }}>
          <div className="cert-controls-left">
            <span className="cert-badge-pill" style={{ color: cheatSheet.badgeColor || '#10b981', borderColor: cheatSheet.badgeColor || '#10b981' }}>
              <ShieldCheck size={14} /> {cheatSheet.badge}
            </span>
            <span style={{ fontSize: '0.8rem', color: '#94a3b8', fontFamily: "'DM Mono', monospace" }}>
              {cheatSheet.category}
            </span>
          </div>
          <div className="cert-controls-right" style={{ display: 'flex', gap: '8px', alignItems: 'center' }}>
            <button 
              type="button" 
              className="btn-cert-action"
              onClick={handlePrint}
              title="Print or Save as PDF"
            >
              <Printer size={15} />
              <span>Print / PDF</span>
            </button>
            <button 
              type="button" 
              className="btn-cert-action"
              onClick={handleCopyMarkdown}
              title="Copy raw markdown"
            >
              {copied ? <Check size={14} className="text-emerald" /> : <Copy size={14} />}
              <span>{copied ? 'Copied' : 'Copy (.md)'}</span>
            </button>
            <button 
              type="button" 
              className="btn-cert-action"
              onClick={handleDownloadMarkdown}
              title="Download markdown file"
            >
              <Download size={14} />
              <span>Download (.md)</span>
            </button>
            <button 
              type="button" 
              className="btn-cert-action" 
              onClick={onClose}
              aria-label="Close modal"
              style={{ color: '#94a3b8' }}
            >
              <X size={16} />
            </button>
          </div>
        </div>

        {/* Printable Cheat Sheet Document */}
        <div className="cheat-sheet-printable-document" style={{ padding: '36px 40px', color: '#f8fafc' }}>
          {/* Header */}
          <div style={{ borderBottom: '2px solid rgba(56, 189, 248, 0.3)', paddingBottom: '20px', marginBottom: '28px' }}>
            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', flexWrap: 'wrap', gap: '10px' }}>
              <div>
                <span style={{ fontSize: '0.75rem', fontWeight: 800, color: '#38bdf8', letterSpacing: '0.1em', fontFamily: "'DM Mono', monospace" }}>
                  SECLOUDIVE OFFICIAL AWS STUDY GUIDE /// VERIFIED 2026
                </span>
                <h1 style={{ fontSize: '1.6rem', fontWeight: 800, margin: '8px 0 4px', color: '#f1f5f9' }}>
                  {cheatSheet.title}
                </h1>
                <p style={{ fontSize: '0.95rem', color: '#94a3b8', margin: 0 }}>
                  {cheatSheet.subtitle}
                </p>
              </div>
              <div style={{ textAlign: 'right' }}>
                <span style={{ fontSize: '0.75rem', background: 'rgba(56, 189, 248, 0.1)', border: '1px solid rgba(56, 189, 248, 0.25)', padding: '4px 10px', borderRadius: '6px', color: '#38bdf8', fontFamily: "'DM Mono', monospace" }}>
                  FREE-EDUCATIONAL-EDITION
                </span>
              </div>
            </div>
            <p style={{ marginTop: '14px', fontSize: '0.85rem', color: '#cbd5e1', lineHeight: 1.6 }}>
              {cheatSheet.description}
            </p>
          </div>

          {/* Sections */}
          <div style={{ display: 'flex', flexDirection: 'column', gap: '28px' }}>
            {cheatSheet.sections.map((section, idx) => (
              <div key={idx} style={{ background: 'rgba(15, 23, 42, 0.6)', border: '1px solid rgba(148, 163, 184, 0.12)', borderRadius: '10px', padding: '20px' }}>
                <h2 style={{ fontSize: '1.05rem', fontWeight: 700, color: '#38bdf8', margin: '0 0 16px', display: 'flex', alignItems: 'center', gap: '8px' }}>
                  <BookOpen size={16} /> {section.heading}
                </h2>

                <div style={{ display: 'flex', flexDirection: 'column', gap: '14px' }}>
                  {section.items.map((item, itemIdx) => (
                    <div 
                      key={itemIdx} 
                      style={{ 
                        background: '#070b14', 
                        border: '1px solid rgba(148, 163, 184, 0.1)', 
                        borderRadius: '8px', 
                        padding: '14px 16px' 
                      }}
                    >
                      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'baseline', flexWrap: 'wrap', gap: '8px', marginBottom: '6px' }}>
                        <span style={{ fontSize: '0.9rem', fontWeight: 700, color: '#f8fafc', fontFamily: "'DM Mono', monospace" }}>
                          {item.key}
                        </span>
                        <span style={{ fontSize: '0.75rem', color: '#f59e0b', background: 'rgba(245, 158, 11, 0.1)', padding: '2px 8px', borderRadius: '4px', border: '1px solid rgba(245, 158, 11, 0.25)', fontFamily: "'DM Mono', monospace" }}>
                          {item.operator}
                        </span>
                      </div>

                      <p style={{ margin: '0 0 10px', fontSize: '0.82rem', color: '#94a3b8', lineHeight: 1.5 }}>
                        {item.purpose}
                      </p>

                      <pre style={{ margin: 0, padding: '10px 14px', background: 'rgba(15, 23, 42, 0.8)', border: '1px solid rgba(56, 189, 248, 0.15)', borderRadius: '6px', fontSize: '0.78rem', color: '#67e8f9', overflowX: 'auto', fontFamily: "'DM Mono', monospace" }}>
                        <code>{item.example}</code>
                      </pre>
                    </div>
                  ))}
                </div>
              </div>
            ))}
          </div>

          {/* Footer Watermark */}
          <div style={{ marginTop: '36px', paddingTop: '20px', borderTop: '1px solid rgba(148, 163, 184, 0.15)', display: 'flex', justifyContent: 'space-between', alignItems: 'center', fontSize: '0.75rem', color: '#64748b', fontFamily: "'DM Mono', monospace" }}>
            <span>SeCloudive Enterprise Career OS /// Open Educational Resource</span>
            <span>NAEN Studios Verified</span>
          </div>
        </div>
      </div>
    </div>
  )
}

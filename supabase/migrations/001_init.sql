-- Cloud Security Academy backend tables.
-- RLS is enabled without anon/authenticated policies because the Express
-- backend uses the Supabase service_role key server-side. The service_role
-- bypasses RLS; browser clients must never receive this key.

create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key default gen_random_uuid(),
  google_id text unique not null,
  name text,
  email text unique not null,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.progress (
  user_id uuid not null references public.users(id) on delete cascade,
  module_id text not null,
  completed_at timestamptz not null default now(),
  primary key (user_id, module_id)
);

create table if not exists public.scenario_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  scenario_id text not null,
  score integer not null check (score >= 0),
  rating text not null check (rating in ('Excellent', 'Good', 'Needs review')),
  completed_at timestamptz not null default now()
);

create table if not exists public.lab_checklists (
  user_id uuid not null references public.users(id) on delete cascade,
  lab_id text not null,
  item_key text not null,
  checked boolean not null default false,
  primary key (user_id, lab_id, item_key)
);

create index if not exists progress_module_id_idx on public.progress(module_id);
create index if not exists scenario_results_user_id_idx on public.scenario_results(user_id);
create index if not exists scenario_results_scenario_id_idx on public.scenario_results(scenario_id);
create index if not exists lab_checklists_user_id_idx on public.lab_checklists(user_id);
create index if not exists lab_checklists_lab_id_idx on public.lab_checklists(lab_id);

alter table public.users enable row level security;
alter table public.progress enable row level security;
alter table public.scenario_results enable row level security;
alter table public.lab_checklists enable row level security;
